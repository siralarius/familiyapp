using FamilyApp.Core.Calendar;
using FamilyApp.Core.Inventory;
using FamilyApp.Core.Meals;
using FamilyApp.Core.Shopping;
using FamilyApp.Shared.Components;
using FamilyApp.Sync.Transport;
using FamilyApp.Web.Storage;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;

var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<Routes>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");
builder.Services.AddScoped<IShoppingRepository, BrowserShoppingRepository>();
builder.Services.AddScoped<ShoppingListService>();
builder.Services.AddScoped<IInventoryRepository, BrowserInventoryRepository>();
builder.Services.AddScoped<InventoryService>();
builder.Services.AddScoped<IMealPlanRepository, BrowserMealPlanRepository>();
builder.Services.AddScoped<MealPlanService>();
builder.Services.AddScoped<IFamilyEventRepository, BrowserFamilyEventRepository>();
builder.Services.AddScoped<FamilyCalendarService>();
builder.Services.AddScoped<IPeerSyncStatusStore, BrowserPeerSyncStatusStore>();
builder.Services.AddScoped<PeerSyncStatusService>();
await builder.Build().RunAsync();
